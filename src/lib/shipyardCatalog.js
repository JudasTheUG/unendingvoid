export function getLocalizedShipName(ship, lang = 'en') {
  if (!ship) return '';
  if (typeof ship.name === 'object') {
    return ship.name[lang] || ship.name.en || '';
  }
  return ship.name || '';
}

export function getLocalizedShipDesc(ship, lang = 'en') {
  if (!ship) return '';
  if (typeof ship.description === 'object') {
    return ship.description[lang] || ship.description.en || '';
  }
  return ship.description || '';
}
